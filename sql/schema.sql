CREATE TABLE IF NOT EXISTS bills_of_lading (
    id INT AUTO_INCREMENT PRIMARY KEY,
    bl_no VARCHAR(50) NOT NULL UNIQUE,
    serial_no VARCHAR(30) DEFAULT '',
    shipper TEXT,
    consignee TEXT,
    notify_party TEXT,
    pre_carriage VARCHAR(100) DEFAULT '',
    place_of_receipt VARCHAR(100) DEFAULT '',
    ocean_vessel VARCHAR(100) DEFAULT '',
    port_of_loading VARCHAR(100) DEFAULT '',
    port_of_discharge VARCHAR(100) DEFAULT '',
    place_of_delivery VARCHAR(100) DEFAULT '',
    arrival_contact TEXT,
    marks_and_numbers TEXT,
    no_of_pkgs VARCHAR(100) DEFAULT '',
    description_of_goods TEXT,
    gross_weight VARCHAR(50) DEFAULT '',
    measurement VARCHAR(50) DEFAULT '',
    total_containers_words VARCHAR(150) DEFAULT '',
    freight_and_charges TEXT,
    revenue_tons VARCHAR(50) DEFAULT '',
    rate VARCHAR(50) DEFAULT '',
    per_unit VARCHAR(50) DEFAULT '',
    prepaid VARCHAR(50) DEFAULT '',
    collect VARCHAR(50) DEFAULT '',
    exchange_rate VARCHAR(50) DEFAULT '',
    prepaid_at VARCHAR(100) DEFAULT '',
    payable_at VARCHAR(100) DEFAULT '',
    place_of_issue VARCHAR(100) DEFAULT '',
    date_of_issue DATE,
    total_prepaid_national VARCHAR(100) DEFAULT '',
    no_of_original_bl VARCHAR(50) DEFAULT '',
    laden_on_board_date DATE,
    laden_on_board_by VARCHAR(100) DEFAULT '',
    attachment_desc TEXT,
    attachment_marks TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);